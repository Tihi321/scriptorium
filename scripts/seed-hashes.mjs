// Writes src/engine/store/seedHistory.ts: a hash of every version of every seed prompt and template that git knows, plus the
// working-tree file. The engine uses it to tell a prompt in a data folder that was never edited (an older seed version, safe
// to upgrade) from one the owner changed. Run it after editing a file under seed/prompts or seed/templates (a test checks it).
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 })
const hash = (text) => createHash('sha256').update(text.replace(/\r\n/g, '\n')).digest('hex').slice(0, 16)

const tracked = git('ls-files', '-z', '--', 'seed/prompts', 'seed/templates').split('\0').filter(Boolean)
const history = {}
for (const file of tracked) {
  const rel = file.replace(/^seed\//, '')
  const hashes = new Set([hash(readFileSync(path.join(root, file), 'utf8'))])
  const shas = git('log', '--format=%H', '--follow', '--', file).split('\n').filter(Boolean)
  for (const sha of shas) {
    try {
      hashes.add(hash(git('show', `${sha}:${file}`)))
    } catch {
      /* the file did not exist under this name in that commit (a rename): --follow lists it, show can't read it */
    }
  }
  history[rel] = [...hashes].sort()
}

const lines = Object.keys(history)
  .sort()
  .map((rel) => `  ${JSON.stringify(rel)}: [${history[rel].map((h) => `'${h}'`).join(', ')}]`)
const out = `// Generated by scripts/seed-hashes.mjs (yarn seed:hashes). Do not edit by hand.
// The hash (sha256, first 16 hex characters, line endings as LF) of every version of every seed prompt and template, by path below seed/.
import { createHash } from 'node:crypto'

export const SEED_HISTORY: Record<string, string[]> = {
${lines.join(',\n')}
}

export const seedHash = (text: string): string => createHash('sha256').update(text.replace(/\\r\\n/g, '\\n')).digest('hex').slice(0, 16)
`
writeFileSync(path.join(root, 'src', 'engine', 'store', 'seedHistory.ts'), out)
console.log(`seed history: ${tracked.length} files`)
